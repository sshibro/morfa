// The bench files of docs/TARGETS.md §0, deterministic from their arguments (lane B0):
//   tsx scripts/bench/gen-file.ts --kind page --layers 100000 [--seed 0] [--pages 1] [--out fixtures/bench/f100k.json]
//   tsx scripts/bench/gen-file.ts --all           f20k, f100k, f500k, product, board2k (and f2k for the many-files load run)
// `page` extends tests/helpers/design-big-files.ts `heavyPage`: screens of 10 sections × a group of 48 layers (501 layers a screen);
// with seed 0 and 40 screens it is that page byte for byte (20 041 layers, 15.9 MB). Another seed moves and resizes the layers and
// shuffles their kinds (a mulberry32 stream), the structure stays. `product` is `productFile()` (12 452 layers); `board` is a board of
// stickies (`--layers` stickies). The JSON is streamed entry by entry, identical to JSON.stringify of the document, so a 400 MB
// file never becomes one string. The files are not committed (regenerated by seed); fixtures/bench/manifest.json is, with each
// standard file's layers, bytes and sha256: `--all` rewrites it, `--check` regenerates every file and compares.
