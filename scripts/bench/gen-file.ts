import {createInstance} from '../../shared/design/components';
import type {DesignDocument, NodeId, NodeType, SceneNode} from '../../shared/design/types';
import {normalizeDocument} from '../../shared/design/normalize';
import {beginTransaction} from '../../shared/design/transaction';
import {createBoardDocument} from '../../shared/design/board/document';
import {createSticky, insertPieces} from '../../shared/design/board/create';
