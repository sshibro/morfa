import {ROOT} from './lib/targets';

export type FileKind = 'page' | 'product' | 'board' | 'instances' | 'shapes';
/** `pages` (kind `page` only, lane BF): the screens spread over this many pages (named "Страница N": the Russian names are part of the manifest's hashes, see the note in pageFile), for the page-on-demand path of
 *  docs/decisions/big-files.md; absent or 1: one page, byte for byte as before. */
export type GenOptions = {kind: FileKind; layers: number; seed: number; pages?: number};
export const LAYERS_PER_SCREEN = 501;
export const BENCH_DIR = path.join(ROOT, 'fixtures/bench');

/** The files TARGETS names. f2k: the 2 000-layer page of the many-files load run (M5/K1 on dev-4). */
export const STANDARD_FILES: Record<string, GenOptions> = {
  f2k: {kind: 'page', layers: 2_000, seed: 0},
  f20k: {kind: 'page', layers: 20_041, seed: 0},
  f100k: {kind: 'page', layers: 100_000, seed: 0},
  f500k: {kind: 'page', layers: 500_000, seed: 0},
  product: {kind: 'product', layers: 12_452, seed: 0},
  board2k: {kind: 'board', layers: 2_000, seed: 0},
  /** Big files (lane BF): the same layers over many pages, what pages on demand are for. */
  f100k5: {kind: 'page', layers: 100_000, seed: 0, pages: 5},
  f500k25: {kind: 'page', layers: 500_000, seed: 0, pages: 25},
  /** E3: one component and 1 000 instances of it. */
  instances1k: {kind: 'instances', layers: 1_000, seed: 0},
  /** E4: 200 overlapping shapes for a boolean union (seeded; L1's fuzz set replaces it when it lands). */
  bool200: {kind: 'shapes', layers: 200, seed: 1},
};

function mulberry32(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** `heavyPage` with `screens` screens; seed 0 reproduces it exactly. `pages` > 1 spreads the screens over that many pages
 *  (the first keeps the file's page id; the others are `page2`…), each screen placed as on a page of its own. */
// Note: the layer, page and sticky names below are Russian ON PURPOSE. Their bytes are part of the sha256 and size of every standard
// file in fixtures/bench/manifest.json (and double as Cyrillic text-handling data), so changing them would invalidate the manifest.
export function pageFile(layers: number, seed = 0, pages = 1): DesignDocument {
  const screens = Math.max(1, Math.round((layers - 1) / LAYERS_PER_SCREEN));
  const random = seed ? mulberry32(seed) : null;
  const doc = createDocument('page', 'Тяжёлая страница');
  const pageIds: NodeId[] = ['page'];
  for (let p = 2; p <= Math.max(1, pages); p++) {
    const id = `page${p}`;
    doc.nodes[id] = createNode('PAGE', {id, name: `Страница ${p}`, children: []});
    doc.pages.push(id);
    pageIds.push(id);
  }
  const perPage = Math.ceil(screens / pageIds.length);
  let n = 0;
  const add = (type: NodeType, parentId: NodeId, props: Partial<SceneNode>) => {
    const id = `n${++n}`;
    doc.nodes[id] = createNode(type, {...props, id, parentId});
    doc.nodes[parentId].children!.push(id);
    return id;
  };
  const kinds: NodeType[] = ['RECTANGLE', 'TEXT', 'ELLIPSE', 'VECTOR', 'RECTANGLE', 'LINE'];
  for (let s = 0; s < screens; s++) {
    const pageId = pageIds[Math.floor(s / perPage)], onPage = s % perPage;
    const screen = add('FRAME', pageId, {name: `Экран ${s + 1}`, x: (onPage % 8) * 1600, y: Math.floor(onPage / 8) * 2200, width: 1440, height: 2000});
    for (let k = 0; k < 10; k++) {
      const section = add('FRAME', screen, {name: `Секция ${k + 1}`, x: 0, y: k * 200, width: 1440, height: 200});
      const group = add('GROUP', section, {name: `Группа ${k + 1}`, x: 20, y: 20, width: 1400, height: 160});
      for (let i = 0; i < 48; i++) {
        const type = random ? kinds[Math.floor(random() * kinds.length)] : kinds[i % kinds.length];
        const jitter = random ? Math.round(random() * 8) : 0;
        const width = random ? 60 + Math.round(random() * 40) : 100;
        add(type, group, {x: 20 + (i % 12) * 110 + jitter, y: 20 + Math.floor(i / 12) * 38, width, height: type === 'LINE' ? 0 : 30, ...(type === 'TEXT' ? {text: defaultTextProps('Текст')} : {})});
      }
    }
  }
  return normalizeDocument(doc, new Set(Object.keys(doc.nodes)), {measurer: testMeasurer});
}

/** A board of `count` stickies in rows of 50, their text fitted (the board's normalization steps installed). */
export function boardFile(count: number): DesignDocument {
  installBoardSteps();
  let seq = 0;
  const newId = () => `b${++seq}`;
  const tx = beginTransaction(createBoardDocument('page'));
  const colors = ['yellow', 'blue', 'green', 'pink', 'orange', 'violet'];
  for (let i = 0; i < count; i++)
    insertPieces(tx, createSticky(newId, {x: (i % 50) * 280, y: Math.floor(i / 50) * 280, color: colors[i % colors.length], text: `Идея ${i + 1}: что улучшить в онбординге`}), 'page');
  return tx.commit({measurer: testMeasurer}).doc;
}

/** One card component (auto layout: a picture, a title, a text) and `count` instances of it in rows of 25. */
export function instancesFile(count: number): DesignDocument {
  const doc = createDocument('page', 'Экземпляры');
  const add = (node: SceneNode, parentId: NodeId) => {
    doc.nodes[node.id] = {...node, parentId};
    doc.nodes[parentId] = {...doc.nodes[parentId], children: [...(doc.nodes[parentId].children ?? []), node.id]};
  };
  add(createNode('COMPONENT', {id: 'card', name: 'Карточка', x: -400, y: 0, width: 240, height: 200, autoLayout: {...defaultAutoLayout('VERTICAL'), itemSpacing: 8, paddingLeft: 12, paddingRight: 12, paddingTop: 12, paddingBottom: 12}, layoutSizingVertical: 'HUG', fills: [solid({r: 1, g: 1, b: 1})], cornerRadius: 12}), 'page');
  add(createNode('RECTANGLE', {id: 'card-img', name: 'Картинка', width: 216, height: 120, fills: [solid({r: 0.8, g: 0.85, b: 0.9})], layoutSizingHorizontal: 'FILL'}), 'card');
  add(createNode('TEXT', {id: 'card-title', name: 'Заголовок', width: 216, height: 24, text: {...defaultTextProps('Карточка'), textAutoResize: 'HEIGHT'}, layoutSizingHorizontal: 'FILL'}), 'card');
  add(createNode('TEXT', {id: 'card-text', name: 'Текст', width: 216, height: 18, text: {...defaultTextProps('Короткое описание карточки'), textAutoResize: 'HEIGHT'}, layoutSizingHorizontal: 'FILL'}), 'card');
  let next = normalizeDocument(doc, new Set(Object.keys(doc.nodes)), {measurer: testMeasurer});
  for (let i = 0; i < count; i++) {
    const made = createInstance(next, 'card', {parentId: 'page', newId: `i${i + 1}`});
    next = made.doc;
    const placed = next.nodes[made.id];
    next = {...next, nodes: {...next.nodes, [made.id]: {...placed, x: (i % 25) * 260, y: Math.floor(i / 25) * 240}}};
  }
  return normalizeDocument(next, new Set(Object.keys(next.nodes)), {measurer: testMeasurer});
}

/** `count` overlapping shapes (rectangles, ellipses, stars, polygons; rotated) in one frame, from a mulberry32 stream. */
export function shapesFile(count: number, seed: number): DesignDocument {
  const random = mulberry32(seed || 1);
  const doc = createDocument('page', 'Фигуры');
  const add = (node: SceneNode, parentId: NodeId) => {
    doc.nodes[node.id] = {...node, parentId};
    doc.nodes[parentId] = {...doc.nodes[parentId], children: [...(doc.nodes[parentId].children ?? []), node.id]};
  };
  add(createNode('FRAME', {id: 'board', name: 'Фигуры', x: 0, y: 0, width: 1000, height: 1000}), 'page');
  const types: NodeType[] = ['RECTANGLE', 'ELLIPSE', 'STAR', 'POLYGON'];
  for (let i = 0; i < count; i++) {
    const type = types[Math.floor(random() * types.length)];
    const size = 60 + random() * 180;
    add(createNode(type, {id: `s${i + 1}`, x: 100 + random() * 700, y: 100 + random() * 700, width: size, height: size * (0.6 + random() * 0.8), rotation: Math.round(random() * 90),
      fills: [solid({r: random(), g: random(), b: random()})], ...(type === 'STAR' ? {pointCount: 5 + Math.floor(random() * 4), innerRadius: 0.4} : type === 'POLYGON' ? {pointCount: 3 + Math.floor(random() * 6)} : {})}), 'board');
  }
  return normalizeDocument(doc, new Set(Object.keys(doc.nodes)), {measurer: testMeasurer});
}

export function generate(options: GenOptions): DesignDocument {
  if (options.kind === 'instances') return instancesFile(options.layers);
  if (options.kind === 'shapes') return shapesFile(options.layers, options.seed);
  if (options.kind === 'page') return pageFile(options.layers, options.seed, options.pages ?? 1);
  if (options.kind === 'product') {
    if (options.seed) throw Error('The product file has no seed: it is tests/helpers/design-big-files.ts productFile().');
    return productFile();
  }
  return boardFile(options.layers);
}

/** Writes `doc` as JSON, byte for byte JSON.stringify(doc), without building the whole string; returns bytes and sha256. */
export function writeDocumentJson(doc: DesignDocument, file: string): {bytes: number; sha256: string} {
  mkdirSync(path.dirname(file), {recursive: true});
  const fd = openSync(file, 'w');
  const hash = createHash('sha256');
  let bytes = 0, pending: string[] = [], pendingLength = 0;
  const flush = () => {
    if (!pending.length) return;
    const chunk = Buffer.from(pending.join(''), 'utf8');
    writeSync(fd, chunk);
    hash.update(chunk);
    bytes += chunk.length;
    pending = [];
    pendingLength = 0;
  };
  const put = (text: string) => {
    pending.push(text);
    pendingLength += text.length;
    if (pendingLength > 1 << 22) flush();
  };
  try {
    put('{');
    let first = true;
    for (const [key, value] of Object.entries(doc)) {
      if (value === undefined) continue;
      put((first ? '' : ',') + JSON.stringify(key) + ':');
      first = false;
      if (key === 'nodes') {
        put('{');
        let firstNode = true;
        for (const [id, node] of Object.entries(value as Record<string, unknown>)) {
          if (node === undefined) continue;
          put((firstNode ? '' : ',') + JSON.stringify(id) + ':' + JSON.stringify(node));
          firstNode = false;
        }
        put('}');
      } else put(JSON.stringify(value));
    }
    put('}');
    flush();
  } finally {
    closeSync(fd);
  }
  return {bytes, sha256: hash.digest('hex')};
}

export type GeneratedMeta = GenOptions & {name: string; file: string; nodes: number; bytes: number; sha256: string; seconds: number};

export function generateFile(name: string, options: GenOptions, dir = BENCH_DIR): GeneratedMeta {
  const started = performance.now();
  const doc = generate(options);
  const file = path.join(dir, `${name}.json`);
  const written = writeDocumentJson(doc, file);
  return {name, ...options, file: path.relative(ROOT, file), nodes: Object.keys(doc.nodes).length, ...written, seconds: (performance.now() - started) / 1000};
}

function arg(name: string): string | undefined {
  const index = process.argv.indexOf(`--${name}`);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

export const MANIFEST = path.join(BENCH_DIR, 'manifest.json');
type ManifestEntry = Pick<GeneratedMeta, 'kind' | 'layers' | 'seed' | 'nodes' | 'bytes' | 'sha256'> & {pages?: number};
const entry = (meta: GeneratedMeta): ManifestEntry => ({kind: meta.kind, layers: meta.layers, seed: meta.seed, ...(meta.pages && meta.pages > 1 ? {pages: meta.pages} : {}), nodes: meta.nodes, bytes: meta.bytes, sha256: meta.sha256});

const isMain = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(ROOT, 'scripts/bench/gen-file.ts');
if (isMain && process.argv.includes('--check')) {
  const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8')) as Record<string, ManifestEntry>;
  let failures = 0;
  for (const [name, expected] of Object.entries(manifest)) {
    const meta = generateFile(name, STANDARD_FILES[name]);
    const same = meta.sha256 === expected.sha256 && meta.bytes === expected.bytes;
    if (!same) failures++;
    console.log(`${same ? 'ok  ' : 'DIFF'} ${name}: ${meta.nodes} layers, ${meta.bytes} bytes, ${meta.seconds.toFixed(2)} s`);
  }
  process.exit(failures ? 1 : 0);
}
if (isMain && !process.argv.includes('--check')) {
  const names = process.argv.includes('--all') ? Object.keys(STANDARD_FILES) : arg('name') && STANDARD_FILES[arg('name')!] ? [arg('name')!] : [];
  const jobs: [string, GenOptions][] = names.map(name => [name, STANDARD_FILES[name]]);
  if (!jobs.length) {
    const kind = (arg('kind') ?? 'page') as FileKind;
    if (!['page', 'product', 'board', 'instances', 'shapes'].includes(kind)) throw Error('--kind page|product|board|instances|shapes');
    const layers = Number(arg('layers') ?? (kind === 'product' ? 12_452 : 20_041));
    const seed = Number(arg('seed') ?? 0);
    const pages = Number(arg('pages') ?? 1);
    if (!Number.isSafeInteger(layers) || layers < 1 || !Number.isSafeInteger(seed) || seed < 0 || !Number.isSafeInteger(pages) || pages < 1) throw Error('--layers N --seed S --pages P: whole numbers');
    const out = arg('out');
    const name = out ? path.basename(out, '.json') : `${kind}-${layers}-s${seed}${pages > 1 ? `-p${pages}` : ''}`;
    jobs.push([name, {kind, layers, seed, pages}]);
    if (out) {
      const meta = generateFile(name, {kind, layers, seed, pages}, path.dirname(path.resolve(out)));
      console.log(JSON.stringify(meta));
      process.exit(0);
    }
  }
  const made = jobs.map(([name, options]) => generateFile(name, options));
  for (const meta of made) console.log(JSON.stringify(meta));
  if (process.argv.includes('--all')) writeFileSync(MANIFEST, JSON.stringify(Object.fromEntries(made.map(meta => [meta.name, entry(meta)])), null, 2) + '\n');
}
