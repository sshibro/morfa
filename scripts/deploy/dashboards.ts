// Writes the Grafana dashboards and the Prometheus recording rules of the TARGETS rows from scripts/bench/targets.json (lane B5),
// so the loop (close.sh reports) and production show every row under the same id:
//   deploy/observability/prometheus/targets-rules.yml       morfa_target_live{row,metric} — what production measures, in the row's unit
//   deploy/observability/grafana/dashboards/morfa-targets.json   one panel per row id: live value, the latest closing run
//                                                           (morfa_target_actual{row,metric}, scripts/deploy/targets-prom.ts), and
//                                                           the target and ceiling drawn as lines
//   deploy/observability/grafana/dashboards/morfa-services.json  the services themselves (traffic, CPU, memory, drain, checkpoints)
//
//   npx tsx scripts/deploy/dashboards.ts           write them
//   npx tsx scripts/deploy/dashboards.ts --check   fail when the committed files differ (tests/design-deploy-observability.test.ts)
import {readFileSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

type Metric = {key: string; label: string; unit: string; better: 'lower' | 'higher' | 'rule'; target: number | null; ceiling: number | null};
type Row = {id: string; section: string; bench: string; lane: string; cells: string[]; metrics: Metric[]};
type Targets = {rows: Row[]; sections?: Record<string, string> | {id: string; title: string}[]};

const quantile = (q: number, metric: string, selector = '', scale = 1000) =>
  `histogram_quantile(${q}, sum by (le) (rate(${metric}_bucket${selector}[5m])))${scale === 1 ? '' : ` * ${scale}`}`;
const collabCpu = 'sum(rate(process_cpu_seconds_total{job="collab"}[5m]))';
const route = (pattern: string) => `{route=${pattern.includes('|') || pattern.includes('*') ? '~' : ''}"${pattern}",method="GET"}`;

/** What production can measure of each row: row → metric key → PromQL in the row's unit. Every other row shows its closing runs. */
export const LIVE: Record<string, Record<string, string>> = {
  M1: {p50: quantile(0.5, 'collab_op_fanout_seconds'), p95: quantile(0.95, 'collab_op_fanout_seconds'), p99: quantile(0.99, 'collab_op_fanout_seconds')},
  M1b: {p50: quantile(0.5, 'collab_op_ack_seconds'), p95: quantile(0.95, 'collab_op_ack_seconds'), p99: quantile(0.99, 'collab_op_ack_seconds')},
  M5: {m1p99: quantile(0.99, 'collab_op_fanout_seconds'), cpu: collabCpu},
  M8: {catchUp: quantile(0.95, 'collab_catchup_seconds')},
  M10: {cpu: collabCpu},
  D1: {p50: quantile(0.5, 'collab_journal_commit_seconds'), p99: quantile(0.99, 'collab_journal_commit_seconds')},
  S3: {cpu: quantile(0.95, 'collab_checkpoint_seconds')},
  X1: {wall: quantile(0.95, 'render_job_seconds', '{kind="thumbnail"}')},
  X2: {p95: quantile(0.95, 'render_job_seconds', '{kind="png"}')},
  X3: {p95: quantile(0.95, 'render_job_seconds', '{kind="svg"}')},
  X4: {p95: quantile(0.95, 'render_job_seconds', '{kind="pdf"}')},
  A1: {p95: quantile(0.95, 'api_http_request_duration_seconds', route('/api/design-files')), p99: quantile(0.99, 'api_http_request_duration_seconds', route('/api/design-files'))},
  A2: {p95: quantile(0.95, 'api_http_request_duration_seconds', route('/api/design-files/:id/session'))},
  A5: {p95: quantile(0.95, 'api_http_request_duration_seconds', route('/api/design-files/:id/(comments|libraries|versions).*'))},
  K1: {cores: collabCpu, ram: 'sum(process_resident_memory_bytes{job="collab"}) / 1073741824'},
};

const json = (value: unknown) => JSON.stringify(value, null, 1) + '\n';
const grafanaUnit = (unit: string) =>
  ({ms: 'ms', s: 's', 'µs': 'µs', MB: 'decmbytes', GB: 'decgbytes', KB: 'deckbytes', fps: 'none', cores: 'none', '%': 'percent', count: 'none', Hz: 'hertz'})[unit] ?? 'none';

function sectionTitles(targets: Targets): Map<string, string> {
  const titles = new Map<string, string>();
  const raw = targets.sections;
  if (Array.isArray(raw)) for (const section of raw) titles.set(String(section.id), section.title);
  else if (raw) for (const [id, title] of Object.entries(raw)) titles.set(id, typeof title === 'string' ? title : String((title as {title?: string}).title ?? id));
  return titles;
}

export function recordingRules(targets: Targets): string {
  const lines = [
    '# GENERATED by scripts/deploy/dashboards.ts from scripts/bench/targets.json — do not edit by hand.',
    '# morfa_target_live{row,metric}: what production measures of each TARGETS row, in the row\'s unit.',
    'groups:',
    '  - name: morfa-targets',
    '    interval: 30s',
    '    rules:',
  ];
  for (const row of targets.rows) {
    for (const metric of row.metrics) {
      const expr = LIVE[row.id]?.[metric.key];
      if (!expr) continue;
      lines.push('      - record: morfa_target_live', `        expr: ${JSON.stringify(expr)}`, `        labels: {row: ${JSON.stringify(row.id)}, metric: ${JSON.stringify(metric.key)}}`);
    }
  }
  return lines.join('\n') + '\n';
}

type Panel = Record<string, unknown>;

function rowPanel(row: Row, id: number, x: number, y: number): Panel {
  const ruleRow = row.metrics.every(metric => metric.better === 'rule');
  const title = `${row.id} — ${row.cells[1].replace(/`/g, '')}`;
  const description = `${row.cells[2]}: target ${row.cells[3]}, ceiling ${row.cells[4]} (${row.cells[5]}). Lane ${row.lane}, bench ${row.bench}. ` +
    `Live = production's own metrics (morfa_target_live); close = the latest scripts/bench/close.sh run on bench-ru (morfa_target_actual, by profile).`;
  const gridPos = {h: 8, w: 8, x, y};
  if (ruleRow) {
    return {
      id, type: 'stat', title, description, gridPos,
      datasource: {type: 'prometheus', uid: 'prometheus'},
      targets: [{refId: 'A', expr: `max by (profile) (morfa_target_pass{row="${row.id}"})`, legendFormat: 'close {{profile}}'}],
      fieldConfig: {defaults: {mappings: [{type: 'value', options: {'0': {text: 'fails', color: 'red'}, '1': {text: 'passes', color: 'green'}}}], thresholds: {mode: 'absolute', steps: [{color: 'red', value: null}, {color: 'green', value: 1}]}}, overrides: []},
      options: {reduceOptions: {calcs: ['lastNotNull'], fields: '', values: false}, colorMode: 'background', textMode: 'value_and_name'},
    };
  }
  const targetsList: Record<string, unknown>[] = [];
  const overrides: Record<string, unknown>[] = [];
  let ref = 0;
  const nextRef = () => String.fromCharCode(65 + ref++);
  for (const metric of row.metrics) {
    if (LIVE[row.id]?.[metric.key]) targetsList.push({refId: nextRef(), expr: `morfa_target_live{row="${row.id}",metric="${metric.key}"}`, legendFormat: `${metric.label} live`});
    targetsList.push({refId: nextRef(), expr: `morfa_target_actual{row="${row.id}",metric="${metric.key}"}`, legendFormat: `${metric.label} close {{profile}}`});
    if (metric.target !== null) targetsList.push({refId: nextRef(), expr: `vector(${metric.target})`, legendFormat: `target ${metric.label}`});
    if (metric.ceiling !== null) targetsList.push({refId: nextRef(), expr: `vector(${metric.ceiling})`, legendFormat: `ceiling ${metric.label}`});
  }
  overrides.push(
    {matcher: {id: 'byRegexp', options: '^target .*'}, properties: [{id: 'color', value: {mode: 'fixed', fixedColor: 'green'}}, {id: 'custom.lineStyle', value: {fill: 'dash', dash: [10, 6]}}, {id: 'custom.lineWidth', value: 2}]},
    {matcher: {id: 'byRegexp', options: '^ceiling .*'}, properties: [{id: 'color', value: {mode: 'fixed', fixedColor: 'red'}}, {id: 'custom.lineStyle', value: {fill: 'dash', dash: [4, 4]}}, {id: 'custom.lineWidth', value: 2}]},
    {matcher: {id: 'byRegexp', options: '.* close .*'}, properties: [{id: 'custom.drawStyle', value: 'points'}, {id: 'custom.pointSize', value: 8}]},
  );
  return {
    id, type: 'timeseries', title, description, gridPos,
    datasource: {type: 'prometheus', uid: 'prometheus'},
    targets: targetsList.map(target => ({...target, datasource: {type: 'prometheus', uid: 'prometheus'}})),
    fieldConfig: {defaults: {unit: grafanaUnit(row.metrics[0]?.unit ?? ''), custom: {drawStyle: 'line', lineWidth: 1, spanNulls: true, showPoints: 'never'}}, overrides},
    options: {legend: {displayMode: 'list', placement: 'bottom'}, tooltip: {mode: 'multi'}},
  };
}

export function targetsDashboard(targets: Targets): unknown {
  const titles = sectionTitles(targets);
  const panels: Panel[] = [];
  let id = 1, y = 0;
  const sections = [...new Set(targets.rows.map(row => row.section))];
  for (const section of sections) {
    panels.push({id: id++, type: 'row', title: `§${section} ${titles.get(section) ?? ''}`.trim(), collapsed: false, gridPos: {h: 1, w: 24, x: 0, y: y++}, panels: []});
    const rows = targets.rows.filter(row => row.section === section);
    rows.forEach((row, i) => {
      panels.push(rowPanel(row, id++, (i % 3) * 8, y + Math.floor(i / 3) * 8));
    });
    y += Math.ceil(rows.length / 3) * 8;
  }
  return {
    uid: 'morfa-targets', title: 'Morfa — TARGETS rows', tags: ['morfa', 'targets'], editable: false, schemaVersion: 39, version: 1,
    time: {from: 'now-24h', to: 'now'}, refresh: '30s',
    description: 'One panel per docs/TARGETS.md row id (generated by scripts/deploy/dashboards.ts). Dashed green: target; dashed red: ceiling.',
    panels,
  };
}

