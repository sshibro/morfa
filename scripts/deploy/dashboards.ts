export function outputs(): Record<string, string> {
  const targets = JSON.parse(readFileSync(path.join(ROOT, 'scripts/bench/targets.json'), 'utf8')) as Targets;
  return {
    'deploy/observability/prometheus/targets-rules.yml': recordingRules(targets),
    'deploy/observability/grafana/dashboards/morfa-targets.json': json(targetsDashboard(targets)),
    'deploy/observability/grafana/dashboards/morfa-services.json': json(servicesDashboard()),
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const [file, text] of Object.entries(outputs())) {
    const full = path.join(ROOT, file);
    if (check) {
      let current = '';
      try {
        current = readFileSync(full, 'utf8');
      } catch {
        // missing counts as stale
      }
      if (current !== text) {
        console.error(`stale: ${file} (run npx tsx scripts/deploy/dashboards.ts)`);
        stale++;
      }
    } else {
      writeFileSync(full, text);
      console.log(`wrote ${file}`);
    }
  }
  if (stale) process.exit(1);
}
