// Generates shared/design/protocol.ts (the TypeScript types of the co-editing socket) from crates/protocol/schema.json,
// which the co-editing server owns (docs/BACKEND.md §2). Run after the schema changes:
//
//   tsx scripts/protocol/gen-ts.ts          write shared/design/protocol.ts
//   tsx scripts/protocol/gen-ts.ts --check  exit 1 when the file is not what the schema gives (tests run this)
//
// The schema uses a small subset of JSON Schema (object/properties/required, const, enum, oneOf, allOf, $ref, arrays,
// type lists with null); anything else is an error here, so a new construct in the schema is noticed, never guessed.
// Three definitions describe the model's own types (DocumentPatch, SceneNode, DesignDocument): they map to the
// TypeScript types the editor already has (shared/design/patch.ts, types.ts).
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

type Schema = {
  $ref?: string;
  type?: string | string[];
  const?: unknown;
  enum?: unknown[];
  oneOf?: Schema[];
  allOf?: Schema[];
  properties?: Record<string, Schema>;
  required?: string[];
  items?: Schema;
  additionalProperties?: Schema | boolean;
  description?: string;
  default?: unknown;
  [key: string]: unknown;
};

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const SCHEMA_PATH = path.join(repo, 'crates/protocol/schema.json');
export const OUTPUT_PATH = path.join(repo, 'shared/design/protocol.ts');

/** Definitions that are the model's types: the editor's own TypeScript types stand for them. */
const MODEL_TYPES: Record<string, string> = {DocumentPatch: 'DocumentPatch', SceneNode: 'SceneNode', DesignDocument: 'DesignDocument'};

const typeName = (def: string) => {
  // c.hello → ClientHello, s.welcome → ServerWelcome, Peer → ProtocolPeer (no clash with the editor's DesignPeer).
  const [side, rest] = def.includes('.') ? def.split('.') : ['', def];
  const pascal = rest[0].toUpperCase() + rest.slice(1);
  if (side === 'c') return 'Client' + pascal;
  if (side === 's') return 'Server' + pascal;
  return MODEL_TYPES[def] ?? 'Protocol' + pascal;
};

const refName = (ref: string) => {
  const match = /^#\/\$defs\/(.+)$/.exec(ref);
  if (!match) throw new Error(`unsupported $ref ${ref}`);
  return match[1];
};

const literal = (value: unknown) => JSON.stringify(value);
const comment = (text: string | undefined, indent: string) => (text ? `${indent}/** ${text.replace(/\*\//g, '*\\/')} */\n` : '');

function render(schema: Schema, indent: string): string {
  if (schema.$ref) return typeName(refName(schema.$ref));
  if (schema.const !== undefined) return literal(schema.const);
  if (schema.enum) return schema.enum.map(literal).join(' | ');
  if (schema.oneOf) return schema.oneOf.map(part => render(part, indent)).join(' | ');
  if (schema.allOf) return schema.allOf.map(part => render(part, indent)).join(' & ');
  const types = Array.isArray(schema.type) ? schema.type : schema.type ? [schema.type] : [];
  if (!types.length) throw new Error(`a schema without a type: ${JSON.stringify(schema)}`);
  return types.map(type => renderType(type, schema, indent)).join(' | ');
}

function renderType(type: string, schema: Schema, indent: string): string {
  switch (type) {
    case 'string':
      return 'string';
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'null':
      return 'null';
    case 'array':
      if (!schema.items) throw new Error('an array without items');
      return `${wrap(render(schema.items, indent))}[]`;
    case 'object': {
      if (!schema.properties) {
        if (schema.additionalProperties && typeof schema.additionalProperties === 'object') return `Record<string, ${render(schema.additionalProperties, indent)}>`;
        return 'Record<string, unknown>';
      }
      const required = new Set(schema.required ?? []);
      const inner = indent + '  ';
      const lines = Object.entries(schema.properties).map(([key, value]) => `${comment(value.description, inner)}${inner}${key}${required.has(key) ? '' : '?'}: ${render(value, inner)};`);
      return `{\n${lines.join('\n')}\n${indent}}`;
    }
    default:
      throw new Error(`unsupported type ${type}`);
  }
}

const wrap = (text: string) => (/[|&]/.test(text) && !text.startsWith('{') ? `(${text})` : text);

export function generate(schemaText: string): string {
  const schema = JSON.parse(schemaText) as Schema & {$defs: Record<string, Schema>};
  const defs = schema.$defs;
  const out: string[] = [];
  out.push('// GENERATED by scripts/protocol/gen-ts.ts from crates/protocol/schema.json (lane B1 owns the schema). Do not edit:');
  out.push('// run `tsx scripts/protocol/gen-ts.ts` after the schema changes (tests/design-protocol.test.ts checks it is current).');
  out.push("import type {DocumentPatch} from './patch';");
  out.push("import type {DesignDocument, SceneNode} from './types';");
  out.push('');
  out.push(`export const PROTOCOL_VERSION = ${literal(schema['x-protocolVersion'])} as const;`);
  out.push(`export const PROTOCOL_LIMITS = ${JSON.stringify(schema['x-limits'], null, 2).replace(/"(\w+)":/g, '$1:')} as const;`);
  out.push(`export const PROTOCOL_ERROR_STATUS = ${JSON.stringify(schema['x-errorCodes'], null, 2).replace(/"(\w+)":/g, '$1:')} as const;`);
  out.push('');
  for (const [name, def] of Object.entries(defs)) {
    if (name === 'client' || name === 'server' || MODEL_TYPES[name]) continue;
    out.push(`${comment(def.description, '')}export type ${typeName(name)} = ${render(def, '')};`);
  }
  const union = (side: 'client' | 'server') => (defs[side].oneOf ?? []).map(part => typeName(refName(part.$ref!)));
  out.push('');
  out.push(`/** Client → server. */\nexport type ClientMessage = ${union('client').join(' | ')};`);
  out.push(`/** Server → client. */\nexport type ServerMessage = ${union('server').join(' | ')};`);
  const tags = (side: 'client' | 'server') => (defs[side].oneOf ?? []).map(part => {
    const def = defs[refName(part.$ref!)];
    const t = def.properties?.t?.const ?? def.allOf?.find(piece => piece.properties?.t)?.properties?.t?.const;
    if (typeof t !== 'string') throw new Error(`${part.$ref} has no tag`);
    return t;
  });
  out.push(`export const CLIENT_TAGS = ${literal(tags('client'))} as const;`);
  out.push(`export const SERVER_TAGS = ${literal(tags('server'))} as const;`);
  out.push(`export type ServerTag = ServerMessage['t'];`);
  out.push('');
  return out.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = generate(fs.readFileSync(SCHEMA_PATH, 'utf8'));
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUTPUT_PATH) ? fs.readFileSync(OUTPUT_PATH, 'utf8') : '';
    if (current !== next) {
      console.error('shared/design/protocol.ts is out of date: run tsx scripts/protocol/gen-ts.ts');
      process.exit(1);
    }
  } else fs.writeFileSync(OUTPUT_PATH, next);
}
