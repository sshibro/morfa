-- Design AI credits (docs/design-tool.md §AI): credit lots with what is left of them, the append-only ledger of every movement,
-- the AI requests with their usage and provider cost, and the credit packs in the design ledger's catalogue. The ledger and the requests are evidence
-- of a prepaid service (refunds are counted from them): the runtime may only add ledger rows, and may add and update requests, never delete either; the lots are a cache of the ledger kept under the account
-- lock and go with the account. No table holds a prompt, a picture or a layer's text.
CREATE TABLE public.design_ai_balances (
  id text COLLATE "C" PRIMARY KEY CHECK(id ~ '^[0-9a-f-]{36}$'),
  user_id text COLLATE "C" NOT NULL CHECK(char_length(user_id) BETWEEN 1 AND 200),
  -- allowance: Pro's credits of one month; trial: the one-time credits of a social sign-up; paid: one pack.
  bucket text COLLATE "C" NOT NULL CHECK(bucket IN('allowance','trial','paid')),
  -- What made the lot, one lot per key: allowance:<the month's start>, trial, or payment:<the payment's id>.
  source text COLLATE "C" NOT NULL CHECK(char_length(source) BETWEEN 1 AND 100),
  granted integer NOT NULL CHECK(granted BETWEEN 1 AND 1000000),
  -- What is left: the ledger's sum for this lot (kept with every ledger row, under the account lock).
  remaining integer NOT NULL CHECK(remaining BETWEEN 0 AND granted),
  -- Spendable until here (a paid lot stays refundable after it).
  expires_at text COLLATE "C" NOT NULL,
  -- A paid lot's payment and what it cost (the refund's price per credit is paid_kopecks / granted).
  payment_id text COLLATE "C" CHECK(payment_id IS NULL OR payment_id ~ '^[0-9a-f-]{36}$'),
  paid_kopecks bigint CHECK(paid_kopecks IS NULL OR paid_kopecks BETWEEN 100 AND 100000000),
  price_version text COLLATE "C" NOT NULL CHECK(char_length(price_version) BETWEEN 1 AND 60),
  created_at text COLLATE "C" NOT NULL,
  UNIQUE(user_id,bucket,source),
  CHECK((bucket='paid')=(payment_id IS NOT NULL AND paid_kopecks IS NOT NULL))
);
-- statement-breakpoint
CREATE INDEX design_ai_balances_user ON public.design_ai_balances(user_id,created_at);
-- statement-breakpoint
-- What the pass looks for: free credits whose time is up.
CREATE INDEX design_ai_balances_lapse ON public.design_ai_balances(expires_at) WHERE remaining>0 AND bucket<>'paid';
-- statement-breakpoint
CREATE TABLE public.design_ai_requests (
  id text COLLATE "C" PRIMARY KEY CHECK(id ~ '^[0-9a-f-]{36}$'),
  user_id text COLLATE "C" NOT NULL CHECK(char_length(user_id) BETWEEN 1 AND 200),
  file_id text COLLATE "C" CHECK(file_id IS NULL OR file_id ~ '^[0-9a-f-]{36}$'),
  action text COLLATE "C" NOT NULL CHECK(action IN('generate','edit','helper')),
  -- The priced variant: low.square, high.portrait, large, ...
  tier text COLLATE "C" NOT NULL CHECK(tier ~ '^[a-z]{1,10}(\.[a-z]{1,10})?$'),
  -- reserved: running; settled: charged; released: nothing charged after the provider may have started (it still counts toward the
  -- daily caps); cancelled: never reached the provider (counts nothing).
  status text COLLATE "C" NOT NULL CHECK(status IN('reserved','settled','released','cancelled')),
  reserved integer NOT NULL CHECK(reserved BETWEEN 1 AND 1000),
  settled integer CHECK(settled IS NULL OR settled BETWEEN 1 AND reserved),
  provider_started integer NOT NULL DEFAULT 0 CHECK(provider_started IN(0,1)),
  model text COLLATE "C" CHECK(model IS NULL OR char_length(model) BETWEEN 1 AND 120),
  input_tokens integer CHECK(input_tokens IS NULL OR input_tokens>=0),
  image_input_tokens integer CHECK(image_input_tokens IS NULL OR image_input_tokens>=0),
  output_tokens integer CHECK(output_tokens IS NULL OR output_tokens>=0),
  -- The provider's cost in rubles, the agent's VAT included; the ceiling's cost when the provider started and reported nothing.
  cost_rub double precision CHECK(cost_rub IS NULL OR cost_rub>=0),
  error text COLLATE "C" CHECK(error IS NULL OR error ~ '^[a-z0-9_]{1,64}$'),
  price_version text COLLATE "C" NOT NULL CHECK(char_length(price_version) BETWEEN 1 AND 60),
  created_at text COLLATE "C" NOT NULL,
  finished_at text COLLATE "C",
  CHECK((status='settled')=(settled IS NOT NULL)),
  CHECK((status='reserved')=(finished_at IS NULL))
);
-- statement-breakpoint
-- The daily caps read an account's last 24 hours.
CREATE INDEX design_ai_requests_user ON public.design_ai_requests(user_id,created_at);
-- statement-breakpoint
-- The monthly budget reads everyone's month; the pass looks for requests left running by a process that stopped.
CREATE INDEX design_ai_requests_month ON public.design_ai_requests(created_at);
-- statement-breakpoint
CREATE INDEX design_ai_requests_running ON public.design_ai_requests(created_at) WHERE status='reserved';
-- statement-breakpoint
CREATE TABLE public.design_ai_ledger (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id text COLLATE "C" NOT NULL CHECK(char_length(user_id) BETWEEN 1 AND 200),
  -- The lot it moves (design_ai_balances.id; the lot row goes with the account, the ledger stays).
  lot_id text COLLATE "C" NOT NULL CHECK(lot_id ~ '^[0-9a-f-]{36}$'),
  -- grant (allowance, trial) and purchase (a pack) make a lot; reserve holds credits for a request; release gives a hold back; settle
  -- charges a request; refund takes refunded credits out (and puts them back if the refund is cancelled); expire ends free credits.
  kind text COLLATE "C" NOT NULL CHECK(kind IN('grant','purchase','reserve','settle','release','refund','expire')),
  bucket text COLLATE "C" NOT NULL CHECK(bucket IN('allowance','trial','paid')),
  credits integer NOT NULL CHECK(credits<>0 AND credits BETWEEN -1000000 AND 1000000),
  request_id text COLLATE "C" CHECK(request_id IS NULL OR request_id ~ '^[0-9a-f-]{36}$'),
  payment_id text COLLATE "C" CHECK(payment_id IS NULL OR payment_id ~ '^[0-9a-f-]{36}$'),
  refund_id text COLLATE "C" CHECK(refund_id IS NULL OR refund_id ~ '^[0-9a-f-]{36}$'),
  price_version text COLLATE "C" NOT NULL CHECK(char_length(price_version) BETWEEN 1 AND 60),
  -- A settle row's share of the request's provider cost, rubles.
  cost_rub double precision CHECK(cost_rub IS NULL OR cost_rub>=0),
  created_at text COLLATE "C" NOT NULL,
  CHECK(kind NOT IN('grant','purchase','release') OR credits>0),
  CHECK(kind NOT IN('reserve','settle','expire') OR credits<0),
  CHECK(kind NOT IN('reserve','settle','release') OR request_id IS NOT NULL),
  CHECK(kind<>'purchase' OR (bucket='paid' AND payment_id IS NOT NULL)),
  CHECK(kind<>'refund' OR (bucket='paid' AND refund_id IS NOT NULL))
);
-- statement-breakpoint
-- One grant or purchase per lot, one hold and one reversal per refund and lot, one reserve, release and settle per request and lot. An
-- expiry is written whenever a lapsed free lot holds credits (a hold given back after its date ends at once).
CREATE UNIQUE INDEX design_ai_ledger_made ON public.design_ai_ledger(lot_id) WHERE kind IN('grant','purchase');
-- statement-breakpoint
CREATE UNIQUE INDEX design_ai_ledger_refund ON public.design_ai_ledger(refund_id,lot_id,(credits>0)) WHERE kind='refund';
-- statement-breakpoint
CREATE UNIQUE INDEX design_ai_ledger_request ON public.design_ai_ledger(request_id,lot_id,kind) WHERE request_id IS NOT NULL;
-- statement-breakpoint
CREATE INDEX design_ai_ledger_user ON public.design_ai_ledger(user_id,id);
